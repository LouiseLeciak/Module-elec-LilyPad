// 2 - MOSI -> D51 (PB2)          |              |    1    2    3    4     5             |
// 3 - DC   ->  D11 (PB6)         |     LCD      |  -[R1]-[R1]-[R1]-[R1]-[R1]-- center   |
// 4 - RST  ->  D12 (PB7)         |              |  -[R2]-[R2]-[R2]-[R2]-[R2]--          |
// 5 - CS   -> D10 (PB5)          |              |            GND                        |
//                                 ------------------------------------------------------
// Power pins:
//   VCC  -> 3.3V -> BOTTOM LINE + BREAD BOARD
//   VCC  -> 5V -> TOP LINE + BREAD BOARD
//   GND  -> GND


