void drawEyeLeft(int x0, int y0, uint16_t fg, uint16_t bg) {
    for (int y = 0; y < 50; y++) {
        for (int byte = 0; byte < 10; byte++) {

            uint8_t b = lookleft[y * 10 + byte];   // FLAT ARRAY INDEX

            for (int bit = 0; bit < 8; bit++) {
                int x = byte * 8 + bit;
                uint8_t pixel = (b >> (7 - bit)) & 1;
                draw_pixel(x0 + x, y0 + y, pixel ? fg : bg);
            }
        }
    }
}




