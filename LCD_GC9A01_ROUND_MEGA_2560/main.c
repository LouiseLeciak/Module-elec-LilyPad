void GC9A01_draw_color_screen(uint8_t screen, uint16_t color) {
    if (screen == LEFT_EYE) {
        set_window(LEFT_EYE, 0, 0, MAX_PIXEL_WIDTH - 1, MAX_PIXEL_HIGH - 1);
        uint8_t hi = color >> 8;
        uint8_t lo = color & 0xFF;
        DC_HIGH();
        CS_LEFT_EYE_LOW();
        for (uint32_t i = 0; i < (uint32_t)MAX_PIXEL_WIDTH * MAX_PIXEL_HIGH; i++) {
        
            spi_send(hi);
            spi_send(lo);
        }
        CS_LEFT_EYE_HIGH();
    } else if (screen == RIGHT_EYE) {
        set_window(RIGHT_EYE, 0, 0, MAX_PIXEL_WIDTH - 1, MAX_PIXEL_HIGH - 1);
        uint8_t hi = color >> 8;
        uint8_t lo = color & 0xFF;
        DC_HIGH();
        CS_RIGHT_EYE_LOW();
        for (uint32_t i = 0; i < (uint32_t)MAX_PIXEL_WIDTH * MAX_PIXEL_HIGH; i++) {
        
            spi_send(hi);
            spi_send(lo);
        }
        CS_RIGHT_EYE_HIGH();
    }

    
}

uint8_t reverse_bits(uint8_t b) {
    b = (b & 0xF0) >> 4 | (b & 0x0F) << 4;
    b = (b & 0xCC) >> 2 | (b & 0x33) << 2;
    b = (b & 0xAA) >> 1 | (b & 0x55) << 1;
    return b;
}


